import { NextRequest, NextResponse } from "next/server";
import { StorageAdapter } from "@/lib/storage/adapter";

export async function GET(
  req: NextRequest,
  { params }: { params: { id: string } }
) {
  try {
    const { searchParams } = new URL(req.url);
    const format = searchParams.get("format") || "markdown";

    const investigation = await StorageAdapter.getInvestigation(params.id);
    if (!investigation) {
      return NextResponse.json(
        { success: false, error: "Investigation not found" },
        { status: 404 }
      );
    }

    if (format === "json") {
      return new NextResponse(JSON.stringify(investigation, null, 2), {
        status: 200,
        headers: {
          "Content-Type": "application/json",
          "Content-Disposition": `attachment; filename="proofforge-investigation-${investigation.id}.json"`,
        },
      });
    }

    // Markdown Export
    const md = `
# ProofForge AI: Research Verification Report
**ID**: \`${investigation.id}\`
**Query**: "${investigation.query}"
**Generated**: ${investigation.completedAt || investigation.updatedAt}
**Epistemic Verdict**: **${(investigation.verdict || "IN_PROGRESS").replace(/_/g, " ")}**

---

## 1. Executive Summary & Stability Metrics
- **Conclusion Stability Index**: **${investigation.metrics?.conclusionStabilityIndex ?? "N/A"}%**
- **Overall Confidence**: **${investigation.metrics?.overallConfidence ?? "N/A"}%**
- **Epistemic Fragility Risk**: **${investigation.metrics?.epistemicFragilityRisk ?? "N/A"}**
- **Evidence Coverage**: **${investigation.metrics?.evidenceCoverage ?? "N/A"}%**
- **Mutation Resilience Score**: **${investigation.metrics?.mutationResilienceScore ?? "N/A"}%**

${investigation.executiveReport || investigation.summary || "Investigation in progress."}

---

## 2. Decomposed Claims & Truth Calibration
${investigation.claims
  .map(
    (c, i) => `
### Claim ${i + 1}: ${c.statement}
- **Category**: ${c.category}
- **Prior Confidence**: ${(c.priorConfidence * 100).toFixed(0)}%
- **Post-Skeptic Confidence**: ${(c.postConfidence * 100).toFixed(0)}%
- **Post-Mutation Stability**: ${(c.postMutationConfidence * 100).toFixed(0)}%
- **Fragility Rating**: ${c.fragilityRating}
- **Status**: ${c.status}
- **Associated Evidence Nodes**: ${c.evidenceIds.join(", ") || "None"}
`
  )
  .join("\n")}

---

## 3. Empirical Citations & Evidence Nodes
${investigation.evidence
  .map(
    (e, i) => `
### [${i + 1}] ${e.source.title}
- **Authors**: ${e.source.authors.join(", ")} (${e.source.year})
- **Publication**: ${e.source.publication}
- **DOI/URL**: ${e.source.doi || e.source.url || "N/A"}
- **Credibility**: ${(e.source.credibilityScore * 100).toFixed(0)}% | **Sample Size**: ${e.source.sampleSize || "N/A"}
- **Peer-Reviewed**: ${e.source.isPeerReviewed ? "Yes" : "No"}
- **Snippet**: "${e.snippet}"
`
  )
  .join("\n")}

---

## 4. Adversarial Skeptic Critiques
${investigation.critiques
  .map(
    (cr, i) => `
### Critique ${i + 1}: ${cr.fallacyType} [${cr.severity} Severity]
- **Auditor**: ${cr.challengerAgent}
- **Critique**: ${cr.critiqueText}
- **Suggested Stress Test**: ${cr.suggestedStressTest}
`
  )
  .join("\n")}

---

## 5. Evidence Mutation Stress Tests (Simulations)
> *Epistemic Notice: All mutations below are synthetic perturbations executed to assess conclusion sensitivity. They are explicitly not verified facts.*

${investigation.mutations
  .map(
    (m, i) => `
### Mutation Test ${i + 1}: ${m.mutationType} - ${m.title}
- **Mutated Condition**: ${m.mutatedHypothesis}
- **Original Confidence**: ${(m.originalConfidence * 100).toFixed(0)}% -> **Mutated Confidence**: ${(m.mutatedConfidence * 100).toFixed(0)}% (Delta: ${(m.confidenceDelta * 100).toFixed(0)}%)
- **Test Survived**: ${m.survived ? "YES" : "NO"}
- **Sensitivity Factor**: ${m.sensitivityFactor}
- **Reasoning**: ${m.reasoning}
`
  )
  .join("\n")}

---
*Report generated by ProofForge AI - Automated Multi-Agent Epistemic Verification Engine*
`;

    return new NextResponse(md.trim(), {
      status: 200,
      headers: {
        "Content-Type": "text/markdown; charset=utf-8",
        "Content-Disposition": `attachment; filename="proofforge-report-${investigation.id}.md"`,
      },
    });
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error.message }, { status: 500 });
  }
}

